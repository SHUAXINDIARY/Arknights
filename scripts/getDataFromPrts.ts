(async () => {
  // Refresh albums independently without visiting PRTS or rewriting its data.
  const albumsOnly = process.argv.includes('--only=albums');
  const selectedTasks = albumsOnly ? task.filter(({ dataKey }) => dataKey === 'AlbumList') : task;
  const dataMap = {} as Record<string, ExtractedData>;
  const browser = await puppeteer.launch({
    args: ['--no-sandbox'],
    defaultViewport: {
      width: 1920,
      height: 1080
    }
  });
  try {
    for (let i = 0; i < selectedTasks.length; i++) {
      const { url, fun, name, customFun, dataKey } = selectedTasks[i];
      if (customFun) {
        const data = await customFun(browser, selectedTasks[i])
        console.log(name, data.length)
        dataMap[dataKey] = data
        console.log(`${name} page 关闭`)
      } else {
        if (!fun) {
          throw new Error(`${name} 未提供页面提取函数`)
        }
        const page = await browser.newPage();
        await gotoWithRetry(page, url);
        const data = await page.evaluate(fun as () => Promise<ExtractedData>)
        console.log(name, data.length)
        dataMap[dataKey] = data
        await page.close();
        console.log(`${name} page 关闭`)
      }
    }
  } finally {
    await browser.close();
  }
  const albums = await downloadSirenAlbumCovers(dataMap.AlbumList as SirenAlbum[]);
  fs.writeFileSync('./src/data/Album.ts', `export interface Album {\n  id: string;\n  name: string;\n  img: string;\n  sourceImg: string;\n}\n\n// Generated from ${SIREN_MUSIC_URL}; covers are stored in public/albums.\nexport const AlbumList: Album[] = ${JSON.stringify(albums, null, 2)};\n`);
  delete dataMap.AlbumList;
  if (albumsOnly) return;
  const { saveOperator, saveSkin } = await import('./filterData');
  const operator = saveOperator(dataMap.memberNameAvatarMap);
  const skin: SkinRecord[] = saveSkin(dataMap._skinList);
  dataMap.memberNameAvatarMap = operator;
  dataMap._skinList = skin.map((item) => ({ ...item, skinName: item.skinName.replaceAll(' ', '_') }));
  const mergedDataMap = Object.fromEntries(
    Object.entries(dataMap).map(([key, latestData]) => [
      key,
      prependLatestData(
        latestData,
        previousDataMap[key as keyof typeof previousDataMap] || [],
        key === 'MedalGroupList' ? 'img' : 'name',
      ),
    ])
  );
  await fs.writeFileSync('./src/data/AutoGenerateData.ts', `export const dataMap = ${JSON.stringify(mergedDataMap)}`)
})();
