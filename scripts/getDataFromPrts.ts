const getAatar = () => {
  const [defaultA, ...other] = document.querySelectorAll(".wikitable");
  const data = [] as Partial<{
    name: string,
    img: string,
  }>[];
  // 初始化默认头像
  const name = [] as string[],
    img = [] as string[];
  defaultA.querySelectorAll("td").forEach((item) => {
    item?.textContent && name.push(item?.textContent?.replaceAll?.("\n", ""));
  });
  defaultA.querySelectorAll("th img").forEach((item) => {
    const url = item?.getAttribute?.("data-srcset")?.split?.(" ")?.[0];
    url && img.push(url);
  });
  data.push(
    ...name.map((item, i) => {
      return {
        name: item,
        img: img[i],
      };
    })
  );
  // 初始化其他
  other.forEach((table) => {
    const name = table
      ?.querySelectorAll?.("th")?.[1]
      ?.textContent?.replaceAll("\n", "");
    const img = table
      ?.querySelectorAll("th img")?.[0]
      ?.getAttribute("data-srcset")
      ?.split(" ")[0];
    name && img && data.push({ name, img });
  });
  console.log(data);
  return data
};

// 获取活动列表 https://prts.wiki/w/%E6%B4%BB%E5%8A%A8%E4%B8%80%E8%A7%88
const getActivityList = async () => {
  // 查找所有表格（页面有多个折叠区域，每个区域一个表格）
  const tables = document.querySelectorAll('table.wikitable');
  if (!tables || tables.length === 0) {
    console.error('未找到表格');
    return [];
  }

  console.log(`找到 ${tables.length} 个表格`);

  const results = [] as {
    name: string;
    type: string;
    img: string;
  }[];

  // 遍历所有表格
  tables.forEach((table, tableIndex) => {
    const tbody = table.querySelector('tbody');
    if (!tbody) {
      console.log(`表格 ${tableIndex} 未找到 tbody`);
      return;
    }

    const rows = tbody.querySelectorAll('tr');

    // 跳过表头，从第二行开始
    for (let i = 1; i < rows.length; i++) {
      const row = rows[i];
      const cells = row.querySelectorAll('td');

      // 确保至少有4列
      if (cells.length < 4) {
        continue;
      }

      // 第2列：活动页面（提取链接文本）
      const secondCell = cells[1];
      const link = secondCell.querySelector('a');
      const name = link ? (link.textContent?.trim() || '') : (secondCell.textContent?.trim() || '');

      // 第3列：活动分类（提取链接文本，可能有多个链接）
      const thirdCell = cells[2];
      const typeLinks = thirdCell.querySelectorAll('a');
      let type = '';
      if (typeLinks.length > 0) {
        type = Array.from(typeLinks)
          .map(link => link.textContent?.trim() || '')
          .filter(text => text)
          .join('、'); // 多个分类用顿号连接
      } else {
        type = thirdCell.textContent?.trim() || '';
      }

      // 第4列：官网公告（提取图片URL）
      const fourthCell = cells[3];
      const img = fourthCell.querySelector('img');
      const imgUrl = img ? (img.getAttribute('src') || '') : '';

      // 只有当 name 不为空时才添加
      if (name) {
        results.push({
          name: name,
          type: type,
          img: imgUrl
        });
      }
    }
  });

  // 输出结果
  console.log('解析完成，共', results.length, '条数据');

  return results;
};

